import 'exam.dart';

/// A question that has 4 options but NO usable answer yet — a
/// candidate for MANUAL CORRECTION (governing spec 19 Nov 2026: AI
/// answer inference is parked; the user picks the correct option in
/// the upload flow). The book gave the options (and maybe an
/// explanation / "(Note: …)" as evidence) but no answer line and no
/// matching answer-key entry (File 2: the explanation prose implies
/// the answer). A question the user does not correct stays pending —
/// never guessed. [reason] says why it is pending: 'no-key-entry'
/// (no key entry at all) or 'unknown-key' (the key explicitly
/// says "?").
class PendingQuestion {
  const PendingQuestion({
    required this.text,
    required this.options,
    required this.subject,
    this.explanation = '',
    this.page = 0,
    this.part = '',
    this.reason = 'no-key-entry',
  }) : assert(options.length == 4, 'Pending questions need exactly 4 options');

  final String text;
  final List<String> options;
  final Subject subject;
  final String explanation;
  final int page;
  final String part;
  final String reason;

  /// A pending question has no answer yet, so it is unverified by
  /// definition — the v2 preview shows it as awaiting manual
  /// correction, never as correct.
  String get verificationStatus => 'unverified';

  Map<String, Object?> toMap() => {
    'text': text,
    'option_a': options[0],
    'option_b': options[1],
    'option_c': options[2],
    'option_d': options[3],
    'subject': subject.label,
    'explanation': explanation,
    'page': page,
    'part': part,
    'reason': reason,
  };

  factory PendingQuestion.fromMap(Map<String, dynamic> m) =>
      PendingQuestion(
        text: m['text'] as String? ?? '',
        options: [
          m['option_a'] as String? ?? '',
          m['option_b'] as String? ?? '',
          m['option_c'] as String? ?? '',
          m['option_d'] as String? ?? '',
        ],
        subject: Subject.fromLabel(m['subject'] as String? ?? ''),
        explanation: m['explanation'] as String? ?? '',
        page: m['page'] as int? ?? 0,
        part: m['part'] as String? ?? '',
        reason: m['reason'] as String? ?? 'no-key-entry',
      );
}

/// One MCQ. [options] always has 4 entries; [correctIndex] is 0-3.
class Question {
  Question({
    this.id,
    required this.text,
    required this.options,
    required this.correctIndex,
    required this.subject,
    required this.sourceId,
    required this.sourceLabel,
    this.explanation = '',
    this.page = 0,
    this.part = '',
    this.answerSource = '',
    this.boldOptions = const [],
    bool? answerVerified,
    double? confidence,
    this.originalCorrectIndex,
    this.markProvenance = '',
  }) : answerVerified = answerVerified ?? isVerifiedSource(answerSource),
       confidence = confidence ??
           confidenceForSource(
             answerSource,
             verified: answerVerified ?? isVerifiedSource(answerSource),
           ),
       assert(options.length == 4, 'MCQs need exactly 4 options'),
       assert(correctIndex >= 0 && correctIndex < 4);

  final int? id;
  final String text;
  final List<String> options;
  final int correctIndex;
  final Subject subject;

  /// Which book / past paper this question came from.
  final String sourceId;
  final String sourceLabel;
  final String explanation;

  /// 1-based PDF page this question was parsed from; 0 = unknown
  /// (TXT file / pasted text, or parsed before page tracking).
  /// Set by the page-aware parse (`parseMcqsFromPages`); the upload
  /// screen uses it for the page-range picker.
  final int page;

  /// Book part / section this question belongs to, e.g.
  /// "Pakistan Current Affairs" or "Paper 1" ('' = none assigned).
  /// Assigned by structure detection during the page-aware parse and
  /// preserved through the answer-key join; AI-generated / inferred
  /// questions must set it the same way. The selection screen filters
  /// tests by this field.
  final String part;

  /// How the correct answer was found — the signal source, so the
  /// upload preview can show counts per source and the AI agent can
  /// set it for inferred answers. One of: 'answer-line' (an explicit
  /// "Answer: …" / "Correct Answer: …" / "Ans: …" line), 'key' (the
  /// book's answer key), 'tick' (a ✓/✔ mark on the correct option),
  /// 'bold' (the correct option was rendered bold), 'asterisk' (a `*`
  /// after the correct option — Dogar-style), 'flashcard' (a
  /// flashcard Q&A with no options in the book), 'manual' (the user
  /// set the answer by hand in manual correction — the book gave no
  /// answer), 'ai' (inferred / generated by the AI agent — legacy
  /// rows only; AI generation is parked by the governing spec,
  /// 19 Nov 2026), or '' (unknown — parsed before this field
  /// existed). Precedence when several signals exist:
  /// answer-line > key > tick > bold > asterisk; conflicts are
  /// recorded in [ParseResult.conflicts], never silently resolved.
  final String answerSource;

  /// Verification status for the v2 preview / manual-correction UI
  /// (governing spec 19 Nov 2026): true means the answer comes from
  /// the book's own printed/official signal (answer-line, key, tick,
  /// bold, asterisk, flashcard); false means it was inferred by AI
  /// or the signals conflicted — an unverified answer must never be
  /// presented as correct without review. A PendingQuestion has no
  /// answer yet, so it is unverified by definition. HONEST LIMIT:
  /// the text parser cannot distinguish a PRINTED tick/bold mark
  /// from a STUDENT'S handwritten tick on a scanned page — both
  /// arrive as the same glyph; that distinction needs the v2 vision
  /// step (print is uniform/aligned, handwriting irregular).
  final bool answerVerified;

  /// True when [source] is a printed/official answer signal.
  static bool isVerifiedSource(String source) => const {
    'answer-line',
    'key',
    'tick',
    'bold',
    'asterisk',
    'flashcard',
  }.contains(source);

  /// Confidence score (0–1) for the detected answer — the v2 preview
  /// shows it per question. Deterministic, from the answer source:
  /// an explicit answer line or the book's key is 1.0; a printed
  /// tick / bold / asterisk / flashcard is 0.9 (a strong printed
  /// signal, but a tick on a scanned page could be the student's pen
  /// — see [markProvenance]); an AI-inferred answer is 0.5; unknown
  /// is 0.0. An unverified answer (conflicting signals, or an
  /// OCR-sourced tick/bold) is scaled by 0.6. Never 1.0 for a mark.
  static double confidenceForSource(
    String source, {
    bool verified = true,
  }) {
    final base = switch (source) {
      'answer-line' || 'key' => 1.0,
      'tick' || 'bold' || 'asterisk' || 'flashcard' => 0.9,
      'manual' => 1.0,
      'ai' => 0.5,
      _ => 0.0,
    };
    return verified ? base : (base * 0.6).clamp(0.0, 1.0);
  }

  /// How sure the engine is about the detected answer, 0–1.
  /// Defaults from [confidenceForSource] on [answerSource]; the
  /// parser lowers it when the signals conflict or the mark came
  /// from OCR with unknown provenance.
  final double confidence;

  /// Verification status for the v2 preview: 'verified' (the answer
  /// comes from the book's own printed/official signal), 'unverified'
  /// (AI-inferred, conflicting signals, or an OCR-sourced tick/bold
  /// that could be the student's pen), or 'manually-corrected' (the
  /// user set the answer by hand — see [originalCorrectIndex]).
  String get verificationStatus => originalCorrectIndex != null
      ? 'manually-corrected'
      : (answerVerified ? 'verified' : 'unverified');

  /// Where the answer mark came from: 'printed' (the book's own
  /// typesetting / text layer — a tick/bold here is official),
  /// 'ocr' (read by OCR from a scan or camera photo — a tick/bold
  /// here could be the student's pen, so the question is
  /// UNVERIFIED until the user confirms it), or '' (unknown — the
  /// parse did not record a source). The parser sets it from the
  /// import path ([parseMcqsFromPages] knows which pages were OCR'd).
  final String markProvenance;

  /// The ORIGINAL extracted answer index, kept only when the user
  /// manually corrects the answer ([withCorrection]): [correctIndex]
  /// then holds the corrected answer and this field holds the one
  /// the engine extracted, so the preview can show both and the
  /// correction is never silently lost. Null = never corrected.
  final int? originalCorrectIndex;

  /// Returns a copy with the answer manually corrected to
  /// [newCorrectIndex]: the original extracted answer is kept in
  /// [originalCorrectIndex] (unless one is already kept), the answer
  /// source becomes 'manual' and the answer is verified (the user
  /// confirmed it). Used by the v2 manual-correction UI.
  Question withCorrection(int newCorrectIndex) => copyWith(
    correctIndex: newCorrectIndex,
    originalCorrectIndex: originalCorrectIndex ?? correctIndex,
    answerSource: 'manual',
    answerVerified: true,
    confidence: 1.0,
  );

  /// Which of the 4 options were rendered BOLD in the book, parallel
  /// to [options] (true = bold). The extractor sets it from the font
  /// name (contains "bold"); the parser reads it as the "bold" answer
  /// signal (exactly one bold option = the correct answer). Empty when
  /// the parse did not track boldness. Shuffled together with
  /// [options] by [copyWithShuffledOptions] so the flags stay aligned.
  final List<bool> boldOptions;

  String get correctLetter => String.fromCharCode(65 + correctIndex);

  /// Returns a copy with the given fields replaced (all optional).
  /// Used by the parser to append "(Note: …)" evidence to a
  /// question built by an earlier block (the nearest preceding
  /// question in reading order).
  Question copyWith({
    int? id,
    String? text,
    List<String>? options,
    int? correctIndex,
    Subject? subject,
    String? sourceId,
    String? sourceLabel,
    String? explanation,
    int? page,
    String? part,
    String? answerSource,
    List<bool>? boldOptions,
    bool? answerVerified,
    double? confidence,
    int? originalCorrectIndex,
    String? markProvenance,
  }) {
    return Question(
      id: id ?? this.id,
      text: text ?? this.text,
      options: options ?? this.options,
      correctIndex: correctIndex ?? this.correctIndex,
      subject: subject ?? this.subject,
      sourceId: sourceId ?? this.sourceId,
      sourceLabel: sourceLabel ?? this.sourceLabel,
      explanation: explanation ?? this.explanation,
      page: page ?? this.page,
      part: part ?? this.part,
      answerSource: answerSource ?? this.answerSource,
      boldOptions: boldOptions ?? this.boldOptions,
      answerVerified: answerVerified ?? this.answerVerified,
      confidence: confidence ?? this.confidence,
      originalCorrectIndex:
          originalCorrectIndex ?? this.originalCorrectIndex,
      markProvenance: markProvenance ?? this.markProvenance,
    );
  }

  Question copyWithShuffledOptions(List<int> newOrder) {
    // newOrder[i] = old index that moves to position i.
    final shuffled = newOrder.map((i) => options[i]).toList();
    // Bold flags move with their options, so the flag still marks the
    // same option text after the shuffle.
    final shuffledBold = boldOptions.length == 4
        ? newOrder.map((i) => boldOptions[i]).toList()
        : boldOptions;
    return Question(
      id: id,
      text: text,
      options: shuffled,
      correctIndex: newOrder.indexOf(correctIndex),
      subject: subject,
      sourceId: sourceId,
      sourceLabel: sourceLabel,
      explanation: explanation,
      page: page,
      part: part,
      answerSource: answerSource,
      boldOptions: shuffledBold,
      answerVerified: answerVerified,
      confidence: confidence,
      originalCorrectIndex: originalCorrectIndex,
      markProvenance: markProvenance,
    );
  }

  Map<String, Object?> toMap() => {
    'id': id,
    'text': text,
    'option_a': options[0],
    'option_b': options[1],
    'option_c': options[2],
    'option_d': options[3],
    'correct_index': correctIndex,
    'subject': subject.label,
    'source_id': sourceId,
    'source_label': sourceLabel,
    'explanation': explanation,
    'page': page,
    'part': part,
    'answer_source': answerSource,
    'answer_verified': answerVerified ? 1 : 0,
    'confidence': confidence,
    'mark_provenance': markProvenance,
    'original_correct_index': originalCorrectIndex,
    // Stored as a 4-char "0100" string: sqflite cannot bind a List,
    // and the isolate maps carry the same shape.
    'bold_options': boldOptions.map((b) => b ? '1' : '0').join(),
  };

  factory Question.fromMap(Map<String, Object?> map) => Question(
    id: map['id'] as int?,
    text: map['text'] as String,
    options: [
      map['option_a'] as String,
      map['option_b'] as String,
      map['option_c'] as String,
      map['option_d'] as String,
    ],
    correctIndex: map['correct_index'] as int,
    subject: Subject.fromLabel(map['subject'] as String? ?? ''),
    sourceId: map['source_id'] as String,
    sourceLabel: map['source_label'] as String,
    explanation: map['explanation'] as String? ?? '',
    // Tolerant reads: rows / isolate maps written before page tracking
    // (v1) have no 'page' / 'part' keys; rows written before answer
    // signals (v1.2) have no 'answer_source' / 'bold_options'; rows
    // written before verification tracking (v1.3) have no
    // 'answer_verified' — derive it from the source (AI = unverified).
    page: map['page'] as int? ?? 0,
    part: map['part'] as String? ?? '',
    answerSource: map['answer_source'] as String? ?? '',
    boldOptions: _boldOptionsFromMap(map['bold_options']),
    answerVerified: _answerVerifiedFromMap(map),
    confidence: _confidenceFromMap(map),
    originalCorrectIndex: map['original_correct_index'] as int?,
    markProvenance: map['mark_provenance'] as String? ?? '',
  );
}

/// Parses the stored confidence: a number, or missing (rows written
/// before v1.3) → derive it from the answer source + verification
/// flag, the same default the constructor uses.
double _confidenceFromMap(Map<String, Object?> map) {
  final v = map['confidence'];
  if (v is num) return v.toDouble().clamp(0.0, 1.0);
  final verified = _answerVerifiedFromMap(map);
  return Question.confidenceForSource(
    map['answer_source'] as String? ?? '',
    verified: verified,
  );
}

/// Parses the stored verification flag: a bool / 0-or-1 number /
/// "1"/"true" string, or missing → derive from the answer source
/// (printed/official signals are verified, AI/unknown are not).
bool _answerVerifiedFromMap(Map<String, Object?> map) {
  final v = map['answer_verified'];
  if (v is bool) return v;
  if (v is num) return v != 0;
  if (v is String) return v == '1' || v == 'true';
  return Question.isVerifiedSource(map['answer_source'] as String? ?? '');
}

/// Parses the stored bold flags: the "0100" string [toMap] writes,
/// a `List<int>` / `List<bool>` (defensive), or missing → [].
List<bool> _boldOptionsFromMap(Object? value) {
  if (value is String) {
    return value.split('').map((c) => c == '1').toList();
  }
  if (value is List) {
    return value.map((e) {
      if (e is bool) return e;
      if (e is num) return e != 0;
      return e.toString() == '1';
    }).toList();
  }
  return const [];
}

/// A book / past paper / topic the user uploaded or that ships built-in.
class BookSource {
  const BookSource({
    required this.id,
    required this.title,
    required this.kind,
    this.questionCount = 0,
    this.addedAtIso = '',
    this.isBuiltIn = false,
  });

  final String id;

  /// e.g. "PPSC Past Paper 2023" or "My Dogar Book — GK".
  final String title;

  /// 'book' | 'past_paper' | 'topic' | 'sample'.
  final String kind;
  final int questionCount;
  final String addedAtIso;
  final bool isBuiltIn;

  String get kindLabel {
    switch (kind) {
      case 'past_paper':
        return 'Past Paper';
      case 'topic':
        return 'Topic';
      case 'sample':
        return 'Sample Bank';
      default:
        return 'Book';
    }
  }

  Map<String, Object?> toMap() => {
    'id': id,
    'title': title,
    'kind': kind,
    'question_count': questionCount,
    'added_at': addedAtIso,
    'is_built_in': isBuiltIn ? 1 : 0,
  };

  factory BookSource.fromMap(Map<String, Object?> map) => BookSource(
    id: map['id'] as String,
    title: map['title'] as String,
    kind: map['kind'] as String,
    questionCount: map['question_count'] as int? ?? 0,
    addedAtIso: map['added_at'] as String? ?? '',
    isBuiltIn: (map['is_built_in'] as int? ?? 0) == 1,
  );
}

/// One finished test attempt, as stored in the local database.
class AttemptRecord {
  const AttemptRecord({
    this.id,
    required this.examId,
    required this.examName,
    this.bookTitle = '',
    required this.totalQuestions,
    required this.correct,
    required this.wrong,
    required this.skipped,
    required this.score,
    required this.percent,
    required this.passed,
    required this.durationSeconds,
    required this.attemptedAtIso,
    this.perSubjectJson = '{}',
    this.wrongQuestionIdsJson = '[]',
  });

  final int? id;
  final String examId;
  final String examName;

  /// The book the test was drawn from (the questions' source label,
  /// e.g. "PPSC Current Affairs 40 MCQs"). v1.2: history folders are
  /// truly per-book (grouped by this, not by the exam title). '' for
  /// attempts recorded before v1.2 (or for built-in / mixed sources).
  final String bookTitle;
  final int totalQuestions;
  final int correct;
  final int wrong;
  final int skipped;
  final double score;
  final double percent;
  final bool passed;
  final int durationSeconds;
  final String attemptedAtIso;

  /// JSON: {"General Knowledge": {"correct": 5, "total": 10}, ...}
  final String perSubjectJson;

  /// JSON list of question ids answered wrong (for "Retry wrong only").
  final String wrongQuestionIdsJson;

  Map<String, Object?> toMap() => {
    'id': id,
    'exam_id': examId,
    'exam_name': examName,
    'book_title': bookTitle,
    'total_questions': totalQuestions,
    'correct': correct,
    'wrong': wrong,
    'skipped': skipped,
    'score': score,
    'percent': percent,
    'passed': passed ? 1 : 0,
    'duration_seconds': durationSeconds,
    'attempted_at': attemptedAtIso,
    'per_subject_json': perSubjectJson,
    'wrong_question_ids_json': wrongQuestionIdsJson,
  };

  factory AttemptRecord.fromMap(Map<String, Object?> map) => AttemptRecord(
    id: map['id'] as int?,
    examId: map['exam_id'] as String,
    examName: map['exam_name'] as String,
    bookTitle: map['book_title'] as String? ?? '',
    totalQuestions: map['total_questions'] as int,
    correct: map['correct'] as int,
    wrong: map['wrong'] as int,
    skipped: map['skipped'] as int,
    score: (map['score'] as num).toDouble(),
    percent: (map['percent'] as num).toDouble(),
    passed: (map['passed'] as int? ?? 0) == 1,
    durationSeconds: map['duration_seconds'] as int,
    attemptedAtIso: map['attempted_at'] as String,
    perSubjectJson: map['per_subject_json'] as String? ?? '{}',
    wrongQuestionIdsJson: map['wrong_question_ids_json'] as String? ?? '[]',
  );
}
